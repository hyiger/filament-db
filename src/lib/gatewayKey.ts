/**
 * The secure gateway's API key (src/lib/secureGateway.ts).
 *
 * `FILAMENTDB_API_KEY` in the environment is used as given (the runtime
 * refuses one that is too short) and cannot be rolled from the app. Otherwise the key is random, generated on first start
 * and kept in `<secureDir>/api-key` (owner-readable only), where Settings can
 * show it and roll it.
 */

import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

export const API_KEY_FILE = "api-key";
/** Marks a generated key so it is recognisable in a config file or a leak scan. */
export const API_KEY_PREFIX = "fdb_";

/** 256 bits from the OS generator, URL-safe. */
export function generateApiKey(): string {
  return API_KEY_PREFIX + randomBytes(32).toString("base64url");
}

/** Shortest key the gateway accepts. It answers on a network and never locks
 * out a client that guesses, so a key must be out of guessing range by length;
 * a generated key is 47 characters. */
export const MIN_API_KEY_LENGTH = 32;

/** A key is usable when it is 32-512 printable, space-free ASCII characters:
 * long enough not to be guessed, and safe in an HTTP header. */
export function isUsableApiKey(value: string): boolean {
  return value.length >= MIN_API_KEY_LENGTH && /^[\x21-\x7e]{1,512}$/.test(value);
}

export type ApiKeySource = "env" | "file";

export interface ApiKeyState {
  key: string;
  source: ApiKeySource;
  /** The key file, when the key lives in one. */
  file: string | null;
}

/** Write `content` so a reader never sees a partial file, owner-only. */
export function writeSecretFile(file: string, content: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, content, { mode: 0o600 });
  // An existing file keeps its old mode through writeFileSync; set it outright.
  fs.chmodSync(tmp, 0o600);
  fs.renameSync(tmp, file);
}

function readKeyFile(file: string): string | null {
  let raw: string;
  try {
    raw = fs.readFileSync(file, "utf8");
  } catch {
    return null;
  }
  const key = raw.trim();
  return isUsableApiKey(key) ? key : null;
}

/**
 * The key to use: the environment's, else the stored one, else a new random
 * one (stored). `created` reports that a key was generated by this call.
 */
export function loadOrCreateApiKey(options: {
  envKey: string | null;
  dir: string;
}): ApiKeyState & { created: boolean } {
  if (options.envKey) {
    return { key: options.envKey, source: "env", file: null, created: false };
  }
  const file = path.join(options.dir, API_KEY_FILE);
  const stored = readKeyFile(file);
  if (stored) return { key: stored, source: "file", file, created: false };
  const key = generateApiKey();
  writeSecretFile(file, key + "\n");
  return { key, source: "file", file, created: true };
}

/** Replace the stored key with a new random one and return it. */
export function rollStoredApiKey(dir: string): ApiKeyState {
  const file = path.join(dir, API_KEY_FILE);
  const key = generateApiKey();
  writeSecretFile(file, key + "\n");
  return { key, source: "file", file };
}
